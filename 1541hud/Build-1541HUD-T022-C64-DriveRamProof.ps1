[CmdletBinding()]
param(
    [string]$OutputDirectory = ""
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
    $scriptDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
    $OutputDirectory = Join-Path $scriptDirectory "build-address-test"
}

# C64 PRG: 10 SYS2061.
# It uses standard DOS M-W/M-E at device 8 to execute:
#   LDA #$A5 / STA $06FF / RTS
# Then it reads $06FF back through M-R.  Green border = pass, red border = fail.
# No IEC address bytes, ROM slots, flash, or persistent drive state are modified.
$basicStub = [byte[]](0x0B,0x08,0x0A,0x00,0x9E,0x32,0x30,0x36,0x31,0x00,0x00,0x00)

# KERNAL: SETLFS, SETNAM, OPEN, CHKOUT, CHROUT, CLRCHN, CHKIN, CHRIN, CLOSE.
# First payload begins at $0864; M-R payload begins at $0877.
$machineCode = [byte[]](
    0xA9,0x0F,0xA2,0x08,0xA0,0x0F,0x20,0xBA,0xFF,
    0xA9,0x00,0xAA,0xA8,0x20,0xBD,0xFF,0x20,0xC0,0xFF,
    0xA9,0x0F,0x20,0xC9,0xFF,
    0xA2,0x00,
    0xBD,0x64,0x08,0x20,0xD2,0xFF,0xE8,0xE0,0x13,0xD0,0xF5,
    0xA2,0x00,
    0xBD,0x77,0x08,0x20,0xD2,0xFF,0xE8,0xE0,0x07,0xD0,0xF5,
    0x20,0xCC,0xFF,0xA9,0x0F,0x20,0xC6,0xFF,0x20,0xCF,0xFF,0x48,
    0x20,0xCC,0xFF,0xA9,0x0F,0x20,0xC3,0xFF,0x68,0xC9,0xA5,0xF0,0x06,
    0xA9,0x02,0x8D,0x20,0xD0,0x60,
    0xA9,0x05,0x8D,0x20,0xD0,0x60
)

$writeExecute = [byte[]](
    0x4D,0x2D,0x57,0x00,0x06,0x06,0xA9,0xA5,0x8D,0xFF,0x06,0x60,0x0D,
    0x4D,0x2D,0x45,0x00,0x06,0x0D
)
$readMarker = [byte[]](0x4D,0x2D,0x52,0xFF,0x06,0x01,0x0D)

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
$outFile = Join-Path $OutputDirectory "1541HUD_UB3_T0.0.22_Drive_RAM_Proof.prg"
[System.IO.File]::WriteAllBytes($outFile, [byte[]](0x01, 0x08) + $basicStub + $machineCode + $writeExecute + $readMarker)

Get-FileHash -Algorithm SHA256 $outFile
Get-Item $outFile | Select-Object Name, Length, LastWriteTime
Write-Host ""
Write-Host "T0.0.22 C64-to-1541 RAM execution proof built."
Write-Host "Run with the drive idle at device 8. Green C64 border = PASS; red = FAIL."
